export function BaseIcon({
  size = 24,
  width,
  height,
  children,
  ...props
}: IconProps): ReactElement {
  return (
    <svg
      height={height || size}
      viewBox={props.viewBox || "0 0 24 24"}
      width={width || size}
      {...props}
    >
      {children}
    </svg>
  );
}

export function Icon({
  id,
  size = 24,
  width,
  height,
  ...props
}: IconProps & { id: IconId }): ReactElement {
  const icon = iconMap.get(id);

  if (!icon) return <div />;

  return createElement(icon, {
    size,
    width: width ?? size,
    height: height ?? size,
    ...props,
  });
}
